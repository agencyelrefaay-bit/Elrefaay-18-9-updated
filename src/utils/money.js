// كل القيم المالية في النظام لازم تُقرَّب لأقرب قرش قبل التخزين، وإلا هتتراكم
// أخطاء الفاصلة العائمة (floating point) بمرور الوقت عبر آلاف الفواتير والدفعات
// (مثال كلاسيكي: 0.1 + 0.2 في JavaScript = 0.30000000000000004).
// هذه الدالة تُستخدم في كل مكان بيُحسب فيه مبلغ مالي قبل ما يتخزن في القاعدة.
function round2(n) {
  const num = Number(n) || 0;
  return Math.round((num + Number.EPSILON) * 100) / 100;
}

module.exports = { round2 };
